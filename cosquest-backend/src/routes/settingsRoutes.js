const router = require('express').Router();
const rateLimit = require('express-rate-limit');
const { requireAuth, requireCompletedOnboarding } = require('../middleware/auth');
const { asyncHandler } = require('../utils/asyncHandler');
const { loginLimiter } = require('../middleware/rateLimiter');
const settings = require('../controllers/settingsController');
const authenticated = [requireAuth, requireCompletedOnboarding];
router.get('/settings', ...authenticated, asyncHandler(settings.getSettings));
router.get('/account', ...authenticated, settings.getAccount);
router.patch('/account', ...authenticated, loginLimiter, asyncHandler(settings.updateAccount));
router.patch('/password', ...authenticated, loginLimiter, asyncHandler(settings.changePassword));
router.get('/preferences/notifications', ...authenticated, settings.getNotifications);
router.get('/appearance', ...authenticated, settings.getAppearance);
router.patch('/appearance', ...authenticated, asyncHandler(settings.updateAppearance));
router.get('/data-usage', ...authenticated, settings.getDataUsage);
router.patch('/data-usage', ...authenticated, asyncHandler(settings.updateDataUsage));
router.get('/help', ...authenticated, settings.getHelp);
router.post('/support-requests', ...authenticated, rateLimit({ windowMs: 60 * 60 * 1000, max: 10, keyGenerator: (req) => String(req.userId), skip: () => process.env.NODE_ENV === 'test' }), asyncHandler(settings.createSupportRequest));
module.exports = router;
