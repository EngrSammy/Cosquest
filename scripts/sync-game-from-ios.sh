#!/usr/bin/env bash
#
# Copies the CostQuest game's sources from ubmids/costquest-ios into the
# merged app's game module (modules/costquest-game/ios/Game), then applies the
# small embedding patches in modules/costquest-game/ios/patches.
#
#   scripts/sync-game-from-ios.sh                 latest costquest-ios main
#   scripts/sync-game-from-ios.sh <sha|branch>    a specific commit
#   COSTQUEST_IOS_DIR=~/src/costquest-ios scripts/sync-game-from-ios.sh
#                                                 use an existing checkout as is
#
# What it changes on the way in, and nothing else:
#   - CostQuestApp.swift loses the `@main struct CostQuestApp: App` and its
#     UIKit delegate (the merged app has its own); AppRoot stays.
#   - Info.plist, the entitlements, the bridging header and the AppIcon are
#     left out (the config plugin merges what is needed into the app's own;
#     the bridging header becomes the module's public header).
#   - Image("Logo") / Color("LaunchBackground") read from the module's
#     resource bundle instead of the main bundle.
#   - patches/*.patch, in name order, with `patch -p1 --forward`.
#     A patch that no longer applies stops the sync with the file named:
#     fix the patch against the new upstream, then run this again.
#
# Writes modules/costquest-game/UPSTREAM (the commit copied) and, when the
# Unity pin moved, says so: FRAMEWORK_PIN.md is copied next to it and
# scripts/fetch-unity-framework.sh reads it from there.
#
# Needs: git (ssh access to ubmids/costquest-ios), python3, patch, rsync.
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MOD="$APP_DIR/modules/costquest-game"
DEST="$MOD/ios/Game"
REF="${1:-main}"
REPO="${COSTQUEST_IOS_REPO:-git@github.com:ubmids/costquest-ios.git}"

if [ -n "${COSTQUEST_IOS_DIR:-}" ]; then
  SRC="$COSTQUEST_IOS_DIR"
else
  SRC="$(mktemp -d)/costquest-ios"
  trap 'rm -rf "$(dirname "$SRC")"' EXIT
  echo "==> cloning $REPO ($REF)"
  git clone -q "$REPO" "$SRC"
  git -C "$SRC" checkout -q "$REF"
fi
SHA="$(git -C "$SRC" rev-parse HEAD)"
SUBJECT="$(git -C "$SRC" log -1 --format=%s)"
echo "==> costquest-ios $SHA ($SUBJECT)"

[ -f "$SRC/CostQuest/CostQuestApp.swift" ] || { echo "not a costquest-ios checkout: $SRC" >&2; exit 1; }

rm -rf "$DEST"
mkdir -p "$DEST"
rsync -a \
  --exclude 'Info.plist' \
  --exclude 'CostQuest.entitlements' \
  --exclude 'CostQuest-Bridging-Header.h' \
  --exclude 'Assets.xcassets' \
  --exclude 'Resources/Packs' \
  --exclude '.DS_Store' \
  "$SRC/CostQuest/" "$DEST/"

# The two named colours/images the game draws, as the module's own catalog.
CAT="$MOD/ios/Resources/CostQuestGame.xcassets"
rm -rf "$CAT"
mkdir -p "$CAT"
cp "$SRC/CostQuest/Assets.xcassets/Contents.json" "$CAT/"
cp -R "$SRC/CostQuest/Assets.xcassets/Logo.imageset" "$CAT/"
cp -R "$SRC/CostQuest/Assets.xcassets/LaunchBackground.colorset" "$CAT/"
# Fonts go to the resource bundle too (registered at runtime, see GameFonts.swift).
mkdir -p "$MOD/ios/Resources/Fonts"
rm -f "$MOD/ios/Resources/Fonts/"*
mv "$DEST/Resources/Fonts/"* "$MOD/ios/Resources/Fonts/"
rm -rf "$DEST/Resources"

# The C surface the Swift sources use, as the module's public header.
python3 - "$SRC/CostQuest/CostQuest-Bridging-Header.h" "$MOD/ios/Embed/CostQuestGameBridge.h" <<'PY'
import sys
src, dst = sys.argv[1], sys.argv[2]
body = open(src).read()
open(dst, "w").write(
    "// GENERATED by scripts/sync-game-from-ios.sh from costquest-ios's\n"
    "// CostQuest-Bridging-Header.h. A pod cannot have a bridging header, so the\n"
    "// same declarations are the module's public header: Swift in this pod sees\n"
    "// them through the pod's own module (-import-underlying-module).\n"
    "#pragma once\n\n" + body)
PY

# Strip the @main App struct and its UIKit delegate; keep AppRoot.
python3 - "$DEST/CostQuestApp.swift" <<'PY'
import re, sys
path = sys.argv[1]
s = open(path).read()

def cut_block(text, start_pattern):
    m = re.search(start_pattern, text, re.M)
    if not m:
        raise SystemExit(f"sync: could not find {start_pattern!r} in CostQuestApp.swift; upstream changed, update this script")
    # Include the doc comment lines directly above the declaration.
    start = m.start()
    while start > 0:
        prev_start = text.rfind("\n", 0, start - 1) + 1
        if text[prev_start:start - 1].lstrip().startswith("///"):
            start = prev_start
        else:
            break
    i = text.index("{", m.end() - 1)
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                end = j + 1
                break
    else:
        raise SystemExit("sync: unbalanced braces in CostQuestApp.swift")
    return text[:start] + text[end:].lstrip("\n")

s = cut_block(s, r"^final class CostQuestAppDelegate\b[^{]*\{")
s = cut_block(s, r"^@main\s*\nstruct CostQuestApp\s*:\s*App\s*\{")
if "@main" in s:
    raise SystemExit("sync: an @main is still left in CostQuestApp.swift")
header = ("// [merged-app] Copied from costquest-ios by scripts/sync-game-from-ios.sh,\n"
          "// with the @main App struct and its delegate removed: the CosQuest app is\n"
          "// the app now, and modules/costquest-game/ios/Embed hosts AppRoot.\n")
open(path, "w").write(header + s)
PY

# Named assets come from the module's bundle, not the app's.
python3 - "$DEST" <<'PY'
import os, re, sys
root = sys.argv[1]
n = 0
for dirpath, _, files in os.walk(root):
    for f in files:
        if not f.endswith(".swift"):
            continue
        p = os.path.join(dirpath, f)
        s = open(p).read()
        t = re.sub(r'\bImage\("([A-Za-z0-9_]+)"\)', r'Image("\1", bundle: .costQuestGame)', s)
        t = re.sub(r'\bColor\("([A-Za-z0-9_]+)"\)', r'Color("\1", bundle: .costQuestGame)', t)
        if t != s:
            open(p, "w").write(t)
            n += 1
print(f"==> named assets re-pointed in {n} files")
PY

# The embedding hooks.
for p in "$MOD/ios/patches/"*.patch; do
  [ -e "$p" ] || continue
  echo "==> patch $(basename "$p")"
  if ! (cd "$MOD/ios" && patch -p1 --forward --no-backup-if-mismatch -s < "$p"); then
    echo "sync: $(basename "$p") no longer applies to costquest-ios $SHA. Fix the patch, then re-run." >&2
    exit 1
  fi
done
find "$DEST" -name '*.rej' -o -name '*.orig' | xargs rm -f

cp "$SRC/FRAMEWORK_PIN.md" "$MOD/FRAMEWORK_PIN.md"
cat > "$MOD/UPSTREAM" <<EOF
# What modules/costquest-game/ios/Game was copied from. Written by
# scripts/sync-game-from-ios.sh; do not edit by hand.
COSTQUEST_IOS_REPO=$REPO
COSTQUEST_IOS_SHA=$SHA
COSTQUEST_IOS_SUBJECT=$SUBJECT
SYNCED_AT=$(date -u +%Y-%m-%dT%H:%M:%SZ)
$(awk -F= '/^(UNITY_COMMIT|DUEL_COMMIT|UNITY_EDITOR|FRAMEWORK_SHA256|RELEASE_REPO|RELEASE_TAG)=/ && !seen[$1]++' "$SRC/FRAMEWORK_PIN.md")
EOF

echo "==> $(find "$DEST" -name '*.swift' | wc -l | tr -d ' ') Swift files, $(find "$DEST" -name '*.c' | wc -l | tr -d ' ') C files in modules/costquest-game/ios/Game"
echo "==> UPSTREAM: costquest-ios $SHA. Commit modules/costquest-game together."
