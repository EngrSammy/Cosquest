// Settles the 4 clashes when the game (build 19) meets the latest chat code.
// In each one BOTH sides are needed, so both are kept:
//   components/PushTapHandler.tsx  the game's "handled" memory + Reply / Mark as read
//   eas.json                       the game switches + the Stripe key
//   package.json                   the game's packages + Stripe / task manager
//   package-lock.json              rebuilt afterwards by npm install
// Run from the project folder, during the merge:   node resolve-game-merge.js
const fs = require("fs");

function keepBoth(file, { json = false } = {}) {
  if (!fs.existsSync(file)) return console.log(`NOT FOUND: ${file}`);
  const raw = fs.readFileSync(file, "utf8");
  const crlf = raw.includes("\r\n");
  let s = raw.replace(/\r\n/g, "\n");
  if (!s.includes("<<<<<<< ")) return console.log(`already settled: ${file}`);
  s = s.replace(/^<<<<<<< [^\n]*\n([\s\S]*?)^=======\n([\s\S]*?)^>>>>>>> [^\n]*\n/gm, (_m, ours, theirs) => {
    if (!json) return ours + theirs;
    // JSON: the two blocks need a comma between them.
    const a = ours.replace(/\s*$/, "");
    return (a.endsWith(",") ? a : `${a},`) + "\n" + theirs;
  });
  if (json) JSON.parse(s); // throws if the result isn't valid JSON
  fs.writeFileSync(file, crlf ? s.replace(/\n/g, "\r\n") : s, "utf8");
  console.log(`settled: ${file}`);
}

keepBoth("components/PushTapHandler.tsx");
keepBoth("eas.json", { json: true });
keepBoth("package.json", { json: true });

// The lock file is regenerated by npm install: start from the game's version.
const lock = "package-lock.json";
if (fs.existsSync(lock) && fs.readFileSync(lock, "utf8").includes("<<<<<<< ")) {
  require("child_process").execSync("git checkout --ours package-lock.json", { stdio: "inherit" });
  console.log("package-lock.json: the game's version (npm install updates it next)");
}
console.log("\nNext: npm install, then npx tsc --noEmit");
