        static int Main(string[] args)
        {
            string outPath = Path.GetFullPath(Path.Combine(ThisDir(), "../../features/game/duel/__tests__/golden.json"));
            string trace = null;
            int traceFrom = 0, traceTo = int.MaxValue;
            for (int i = 0; i < args.Length; i++)
            {
                switch (args[i])
                {
                    case "--out": outPath = Path.GetFullPath(args[++i]); break;
                    case "--trace": trace = args[++i]; break;
                    case "--from": traceFrom = int.Parse(args[++i]); break;
                    case "--to": traceTo = int.Parse(args[++i]); break;
                    case "--list":
                        foreach (var c in Cases()) Console.WriteLine(c.Name);
                        return 0;
                    default:
                        Console.Error.WriteLine("usage: DuelGolden [--out golden.json] [--list] [--trace <case> [--from t] [--to t]]");
                        return 2;
                }
            }

            var cases = Cases();
            var names = new HashSet<string>();
            foreach (var c in cases)
                if (!names.Add(c.Name)) throw new Exception("duplicate case name " + c.Name);

            if (trace != null)
            {
                var c = cases.FirstOrDefault(x => x.Name == trace) ?? throw new Exception("no case " + trace);
                Run(c, (sim) =>
                {
                    var s = sim.State;
                    if (s.Tick < traceFrom || s.Tick > traceTo) return;
                    Console.WriteLine($"{s.Tick} {sim.Hash():x16} hs={s.HitStop} left={s.TicksLeft} | {F(s.P1)} | {F(s.P2)}");
                });
                return 0;
            }

            var sb = new StringBuilder();
            sb.Append("{\n");
            sb.Append("\"version\": 1,\n");
            sb.Append("\"about\": ").Append(JsonConvert.ToString(
                "Golden vectors for features/game/duel, generated by scripts/duel-golden from the C# CosQuest.Duel engine. " +
                "Do not edit by hand: regenerate (see scripts/duel-golden/README.md).")).Append(",\n");
            sb.Append("\"engine\": ").Append(EngineInfo().ToString(Formatting.None)).Append(",\n");
            sb.Append("\"checkpointEvery\": ").Append(CheckpointEvery).Append(",\n");
            sb.Append("\"cases\": [\n");
            var stats = new Coverage();
            for (int i = 0; i < cases.Count; i++)
            {
                var o = Golden(cases[i], stats);
                sb.Append(o.ToString(Formatting.None));
                sb.Append(i + 1 < cases.Count ? ",\n" : "\n");
            }
            sb.Append("]\n}\n");
            Directory.CreateDirectory(Path.GetDirectoryName(outPath));
            File.WriteAllText(outPath, sb.ToString(), new UTF8Encoding(false));
            Console.Error.WriteLine($"wrote {cases.Count} cases, {sb.Length / 1024} KiB to {outPath}");
            stats.Report();
            return 0;
        }

