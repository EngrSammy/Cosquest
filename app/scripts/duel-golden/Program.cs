        // ── running one ────────────────────────────────────────────────────

        sealed class Outcome
        {
            public DuelSim Sim;
            public InputLog Log;
            public JArray Checkpoints = new JArray();
            public ulong EventsHash;
            public int[] EventCounts = new int[10];
            public int EventCount;
            public int MaxTicks;
            public Dictionary<string, int> P1Moves = new Dictionary<string, int>();
        }

        static Outcome Run(Case c, Action<DuelSim> perTick = null)
        {
            var setup = c.Setup;
            var o = new Outcome { Sim = new DuelSim(setup), Log = new InputLog() };
            var sim = o.Sim;
            var s1 = setup.P1.Ai == null ? Script.Make(c.Style1, c.ScriptSeed) : null;
            var s2 = setup.P2.Ai == null ? Script.Make(c.Style2, c.ScriptSeed ^ 0xABCDEFUL) : null;
            // InputLog.Replay's own default limit.
            o.MaxTicks = setup.RoundTicks * 4 + 1000;
            var eh = Fnv1a.Start();
            o.Checkpoints.Add(new JArray(0, Hex(sim.Hash())));
            perTick?.Invoke(sim);
            while (!sim.State.Over && sim.State.Tick < o.MaxTicks)
            {
                var k1 = s1 != null ? s1.Next(sim.State, 0) : InputKind.None;
                var k2 = s2 != null ? s2.Next(sim.State, 1) : InputKind.None;
                InputLog.Step(sim, o.Log, InputFrame.Of(k1), InputFrame.Of(k2));
                var ev = sim.DrainEvents();
                for (int i = 0; i < ev.Count; i++)
                {
                    var e = ev[i];
                    eh.Add((int)e.Type); eh.Add(e.Tick); eh.Add(e.Source); eh.Add(e.Target);
                    eh.Add((int)e.Move); eh.Add(e.Damage); eh.Add(e.HitStop); eh.Add(e.X);
                    o.EventCounts[(int)e.Type]++;
                    o.EventCount++;
                    if ((e.Type == DuelEventType.Hit || e.Type == DuelEventType.Blocked) && e.Source == 1)
                    {
                        var key = e.Move.ToString();
                        o.P1Moves[key] = o.P1Moves.TryGetValue(key, out var v) ? v + 1 : 1;
                    }
                }
                int t = sim.State.Tick;
                if (t <= 3 || t % CheckpointEvery == 0) o.Checkpoints.Add(new JArray(t, Hex(sim.Hash())));
                perTick?.Invoke(sim);
            }
            int last = sim.State.Tick;
            if (!(last <= 3 || last % CheckpointEvery == 0)) o.Checkpoints.Add(new JArray(last, Hex(sim.Hash())));
            o.EventsHash = eh.Value;
            return o;
        }

        static JObject Golden(Case c, Coverage cov)
        {
            // The setup as built, before DuelSim's Validate clamps the AI in place.
            var setupJ = SetupJson(c.Setup);
            JObject presentation = null;
            if (c.ServerJson != null)
            {
                var p = DuelWire.Present(DuelWire.Parse(c.ServerJson));
                presentation = new JObject
                {
                    ["p1Name"] = p.P1Name, ["p2Name"] = p.P2Name, ["p1Faction"] = p.P1Faction,
                    ["p2Faction"] = p.P2Faction, ["p1Level"] = p.P1Level, ["p2Level"] = p.P2Level,
                };
            }
            var o = Run(c);
            var sim = o.Sim;
            var s = sim.State;
            var j = new JObject
            {
                ["name"] = c.Name,
            };
            if (c.Note.Length > 0) j["note"] = c.Note;
            j["setup"] = setupJ;
            if (c.Ai1Create != null) j["ai1Create"] = new JArray(c.Ai1Create);
            if (c.Ai2Create != null) j["ai2Create"] = new JArray(c.Ai2Create);
            if (c.ServerJson != null)
                j["server"] = new JObject { ["json"] = c.ServerJson, ["seedText"] = c.SeedText, ["presentation"] = presentation };
            j["styles"] = new JArray(c.Setup.P1.Ai == null ? c.Style1 : "ai", c.Setup.P2.Ai == null ? c.Style2 : "ai");
            j["maxTicks"] = o.MaxTicks;
            // The wire logs are also the scripts: the TS test feeds them back tick by tick.
            j["wire"] = new JObject { ["p1"] = Wire(o.Log.ToWire(0)), ["p2"] = Wire(o.Log.ToWire(1)) };
            j["checkpoints"] = new JArray(o.Checkpoints);
            j["final"] = new JObject
            {
                ["tick"] = s.Tick, ["ticksLeft"] = s.TicksLeft, ["hitStop"] = s.HitStop, ["over"] = s.Over,
                ["winner"] = s.Winner, ["endReason"] = (int)s.EndReason,
                ["hash"] = Hex(sim.Hash()),
                ["eventsHash"] = Hex(o.EventsHash), ["eventCount"] = o.EventCount, ["eventCounts"] = new JArray(o.EventCounts),
                ["p1"] = FighterJson(s.P1), ["p2"] = FighterJson(s.P2),
            };
            // What the verifier does with the wire log (only meaningful when P2 replays itself).
            if (c.Setup.P2.Ai != null)
            {
                var r = InputLog.Replay(c.Setup, InputLog.FromWire(0, o.Log.ToWire(0)));
                j["replay"] = new JObject
                {
                    ["hash"] = Hex(r.Hash), ["winner"] = r.Winner, ["ticks"] = r.Ticks,
                    ["p1Hp"] = r.P1Hp, ["p2Hp"] = r.P2Hp, ["endReason"] = (int)r.EndReason,
                };
                if (r.Hash != sim.Hash()) throw new Exception($"{c.Name}: the C# replay does not reproduce the fight");
            }
            if (c.Finish) j["finishJson"] = DuelWire.FinishJson(sim, o.Log);
            cov.Add(c, o);
            return j;
        }

        static JArray Wire(int[][] w)
        {
            var a = new JArray();
            foreach (var e in w) a.Add(new JArray(e.Select(x => (object)x).ToArray()));
            return a;
        }

