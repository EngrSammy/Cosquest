        static Case Server(string name, JObject setup, string seedText, string style1, string style2, ulong scriptSeed, string note)
        {
            var json = setup.ToString(Formatting.None);
            var w = DuelWire.Parse(json);
            var sim = DuelWire.ToSim(w);
            return new Case
            {
                Name = name, Note = note, Setup = sim, ServerJson = json, SeedText = seedText,
                Style1 = style1, Style2 = style2, ScriptSeed = scriptSeed, Finish = true,
            };
