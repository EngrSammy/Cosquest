        static JObject EngineInfo()
        {
            var dir = typeof(Program).Assembly.GetCustomAttributes<AssemblyMetadataAttribute>()
                .First(a => a.Key == "DuelEngineRuntime").Value;
            var files = Directory.GetFiles(dir, "*.cs", SearchOption.AllDirectories)
                .OrderBy(f => f, StringComparer.Ordinal).ToArray();
            using var sha = SHA256.Create();
            var all = new MemoryStream();
            foreach (var f in files)
            {
                var name = Encoding.UTF8.GetBytes(Path.GetRelativePath(dir, f).Replace('\\', '/') + "\n");
                all.Write(name, 0, name.Length);
                var bytes = File.ReadAllBytes(f);
                all.Write(bytes, 0, bytes.Length);
            }
            var hash = Convert.ToHexString(sha.ComputeHash(all.ToArray())).ToLowerInvariant();
            string commit = null;
            try
            {
                var psi = new System.Diagnostics.ProcessStartInfo("git", $"-C \"{dir}\" log -1 --format=%H -- .")
                { RedirectStandardOutput = true, RedirectStandardError = true, UseShellExecute = false };
                using var p = System.Diagnostics.Process.Start(psi);
                commit = p.StandardOutput.ReadToEnd().Trim();
                p.WaitForExit();
                if (p.ExitCode != 0 || commit.Length == 0) commit = null;
            }
            catch (Exception) { commit = null; }
            return new JObject
            {
                ["package"] = "CosQuest.Duel (costquest-duel/src/CosQuest.Duel/Runtime)",
                ["lastCommit"] = commit,
                ["sourcesSha256"] = hash,
                ["files"] = new JArray(files.Select(f => Path.GetFileName(f)).ToArray()),
            };
        }

        /// <summary>What the cases exercised, so a thin golden set is noticed.</summary>
        sealed class Coverage
        {
            readonly int[] _kinds = new int[10];
            readonly Dictionary<string, int> _ends = new Dictionary<string, int>();
            readonly Dictionary<string, int> _p1Moves = new Dictionary<string, int>();
            readonly HashSet<string> _ai = new HashSet<string>();
            readonly HashSet<WeaponClass> _classes = new HashSet<WeaponClass>();
            int _ticks;

            public void Add(Case c, Outcome o)
            {
                foreach (var side in new[] { 0, 1 })
                    foreach (var e in o.Log.ToWire(side)) _kinds[e[1]] += e.Length == 3 ? e[2] : 1;
                var s = o.Sim.State;
                var key = $"{s.EndReason} winner={s.Winner}";
                _ends[key] = _ends.TryGetValue(key, out var v) ? v + 1 : 1;
                foreach (var kv in o.P1Moves) _p1Moves[kv.Key] = (_p1Moves.TryGetValue(kv.Key, out var m) ? m : 0) + kv.Value;
                foreach (var f in new[] { c.Setup.P1, c.Setup.P2 })
                {
                    _classes.Add(f.Class);
                    if (f.Ai != null) _ai.Add($"{f.Ai.Stance}/{f.Ai.Faction}");
                }
                _ticks += s.Tick;
            }

            public void Report()
            {
                Console.Error.WriteLine($"ticks simulated: {_ticks}");
                Console.Error.WriteLine("human input ticks by kind: " + string.Join(", ",
                    Enumerable.Range(1, 9).Select(k => $"{(InputKind)k}={_kinds[k]}")));
                Console.Error.WriteLine("endings: " + string.Join(", ", _ends.Select(kv => $"{kv.Key}: {kv.Value}")));
                Console.Error.WriteLine("P1 moves that hit or were blocked: " + string.Join(", ", _p1Moves.Select(kv => $"{kv.Key}={kv.Value}")));
                Console.Error.WriteLine($"classes: {string.Join(",", _classes)}; AI stance/faction combos: {_ai.Count}");
                for (int k = 1; k <= 9; k++)
                    if (_kinds[k] == 0) throw new Exception($"no case exercised {(InputKind)k}");
            }
        }
